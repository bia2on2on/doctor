<?php

declare(strict_types=1);

namespace ClinicCore\Domain\Validators;

/**
 * آیا متن «محتوای قابلِ رؤیت» دارد؟ — یک نقطهٔ واحد برای همهٔ ورودی‌های نام.
 *
 * نقصِ واقعیِ پذیرش: نامی که فقط از نویسه‌های نامرئی/صفر-عرض ساخته شده
 * (U+200B صفر-عرض، U+200C نیم‌فاصله، U+200D پیوندِ صفر-عرض، U+200E/U+200F
 * نشانه‌های چپ‌به‌راست/راست‌به‌چپ، U+2060 Word Joiner، U+FEFF BOM) به‌همراهِ
 * فاصله و کنترل‌کاراکترهای ASCII (U+0000 تا U+001F) از اعتبارسنجیِ
 * «خالی نبودن» عبور می‌کرد و در پرونده ذخیره می‌شد.
 *
 * قاعده: فقط وقتی رد می‌شود که پس از حذفِ این نویسه‌ها و فاصله‌ها **هیچ
 * نویسهٔ قابلِ رؤیتی** نمانده باشد؛ نیم‌فاصلهٔ «داخلِ» یک واژهٔ فارسی
 * (مثل «می‌روم») همراهِ حروفِش باقی می‌ماند و نام معتبر است. هیچ بخشی از
 * متن بازنویسی نمی‌شود — این یاردهنده فقط «تصمیم» می‌گیرد.
 *
 * پیاده‌سازیِ UTF-8-امن: الگوی `/u`؛ ورودیِ نامعتبر Fail-Closed رد می‌شود
 * (preg_* مقدارِ null می‌دهد ⇒ «محتوای قابلِ رؤیت ندارد»).
 */
final class VisibleText {

	/**
	 * نویسه‌های «نامرئی» که به‌تنهایی محتوا حساب نمی‌شوند: فاصله‌های ASCII،
	 * کنترل‌کاراکترهای ASCII (U+0000 تا U+001F، از «NUL» تا «US»)، NBSP
	 * U+00A0 و فهرستِ صریحِ نویسههای صفر-عرض/کنترلِ جهت.
	 */
	private const INVISIBLE_CLASS =
		'\\s\\x{0000}-\\x{001F}\\x{00A0}\\x{200B}-\\x{200F}\\x{2060}\\x{FEFF}';

	/**
	 * @param string $value متنِ خام (پس از پاک‌سازیِ مرز، مثل حذفِ کنترل‌کاراکتر).
	 */
	public static function has_visible_content( string $value ): bool {
		if ( '' === $value ) {
			return false;
		}

		$stripped = preg_replace( '/[' . self::INVISIBLE_CLASS . ']+/u', '', $value );
		if ( null === $stripped ) {
			// ورودیِ UTF-8 نامعتبر — Fail-Closed: محتوای قابلِ رؤیتی اثبات نشد.
			return false;
		}

		return '' !== $stripped;
	}
}
