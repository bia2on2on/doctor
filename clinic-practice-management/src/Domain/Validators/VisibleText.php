<?php

declare(strict_types=1);

namespace ClinicCore\Domain\Validators;

/**
 * آیا متن «محتوای قابلِ رؤیت» دارد؟ — یک نقطهٔ واحد برای همهٔ ورودی‌های نام.
 *
 * نقصِ واقعیِ پذیرش: نامی که فقط از نویسه‌های نامرئی/صفر-عرض ساخته شده
 * (نیم‌فاصله U+200C، پیوندِ صفر-عرض U+200D و دیگر نویسه‌های قالب‌بندی)
 * به‌همراهِ فاصله، کنترل‌کاراکترهای ASCII (U+0000 تا U+001F) و جداکننده‌های
 * یونیکد — از جمله U+2009 THIN SPACE که در بازبینی مستقل نام‌برده شد — از
 * اعتبارسنجیِ «خالی نبودن» عبور می‌کرد و در پرونده ذخیره می‌شد.
 *
 * قاعده: فقط وقتی رد می‌شود که پس از حذفِ این نویسه‌ها و فاصله‌ها **هیچ
 * نویسهٔ قابلِ رؤیتی** نمانده باشد؛ نیم‌فاصلهٔ «داخلِ» یک واژهٔ فارسی
 * (مثل «می‌روم») همراهِ حروفِش باقی می‌ماند و نام معتبر است. هیچ بخشی از
 * متن بازنویسی نمی‌شود — این یاردهنده فقط «تصمیم» می‌گیرد.
 *
 * پیاده‌سازیِ UTF-8-امن: الگوی `/u`؛ ورودیِ نامعتبر Fail-Closed رد می‌شود
 * (preg_* مقدارِ null می‌دهد ⇒ «محتوای قابلِ رؤیت ندارد»).
 */
final class VisibleText {

	/**
	 * نویسه‌های «نامرئی» که به‌تنهایی محتوا حساب نمی‌شوند: فاصله‌های ASCII،
	 * کنترل‌کاراکترهای ASCII (U+0000 تا U+001F)، **همهٔ** جداکننده‌های
	 * یونیکد (ردهٔ Z: شامل U+2009 THIN SPACE و خانوادهٔ U+2000–U+200A،
	 * U+3000، U+1680، U+205F، U+202F، جداکنندهٔ خط/بند U+2028/U+2029 و
	 * NBSP U+00A0) و **همهٔ** نویسه‌های قالب‌بندی (ردهٔ Cf: شامل U+200B–U+200F،
	 * U+2060، U+FEFF، U+00AD، U+061C، U+180E، U+202A–U+202E و U+2061–U+2064).
	 *
	 * مرزِ تصمیم روی رده‌های استاندارد یونیکد است، نه فهرستِ دستیِ نویسه؛
	 * نویسهٔ حرف‌دار (Lo/…) هرگز نامرئی حساب نمی‌شود، پس نام‌های معتبرِ
	 * فارسی/لاتین و ZWNJِ داخلِ واژه همان‌طور معتبر می‌مانند.
	 * (باقی‌ماندهٔ آگاهانه: پرکننده‌های نامرئیِ Hangul مانند U+3164 ردهٔ Lo
	 * دارند و خارج از دامنهٔ «جداکننده/قالب‌بندی»اند.)
	 */
	private const INVISIBLE_CLASS =
		'\\s\\x{0000}-\\x{001F}\\p{Z}\\p{Cf}';

	/**
	 * نویسه‌های کنترلِ دوجهتیِ یونیکد (Bidi_Control=Yes): U+061C ARABIC LETTER
	 * MARK (ALM)، U+200E (LRM)، U+200F (RLM)، U+202A–U+202E (LRE/RLE/PDF/LRO/
	 * RLO) و U+2066–U+2069 (LRI/RLI/FSI/PDI). هیچ‌کدام در نامِ واقعیِ شخص
	 * مشروع نیستند؛ فقط برای خراب/جاسوسیِ نمایشِ متن استفاده می‌شوند. حضورِ
	 * هر کدام در نام **رد** می‌شود — هرگز سکوت‌کنان حذف یا جادو-تصحیح.
	 * (نیم‌فاصلهٔ U+200C و پیوندِ صفر-عرض U+200D کنترلِ دوجهتی **نیستند** و
	 * عضوِ این فهرست نیستند؛ در نام‌های فارسی معتبر باقی می‌مانند.)
	 */
	private const BIDI_CONTROL_CLASS =
		'\x{061C}\x{200E}\x{200F}\x{202A}-\x{202E}\x{2066}-\x{2069}';

	/**
	 * @param string $value متنِ خام (پس از پاک‌سازیِ مرز، مثل حذفِ کنترل‌کاراکتر).
	 */
	public static function has_visible_content( string $value ): bool {
		if ( '' === $value ) {
			return false;
		}

		$stripped = preg_replace( '/[' . self::INVISIBLE_CLASS . ']+/u', '', $value );
		if ( null === $stripped ) {
			// ورودیِ UTF-8 نامعتبر — Fail-Closed: محتوای قابلِ رؤیتی اثبات نشد.
			return false;
		}

		return '' !== $stripped;
	}

	/**
	 * @param string $value متنِ خام (پس از پاک‌سازیِ مرز). true یعنی حضورِ
	 * کنترل‌کنترلِ دوجهتی؛ نام‌های تولیدشده توسط انسان معتبر حاویِ آن نیستند.
	 * ورودیِ UTF-8 نامعتبر Fail-Closed (true) می‌گیرد.
	 */
	public static function has_bidi_control( string $value ): bool {
		if ( '' === $value ) {
			return false;
		}

		$found = preg_match( '/[' . self::BIDI_CONTROL_CLASS . ']/u', $value );
		if ( ! is_int( $found ) ) {
			// preg_match روی ورودیِ UTF-8 نامعتبر مقدارِ false می‌دهد (نه null) —
			// Fail-Closed: عدمِ وجود کنترلِ جهت اثبات نشد.
			return true;
		}

		return 1 === $found;
	}
}
